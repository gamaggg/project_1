-- Откат: 01_cron_history_ROLLBACK.sql снимает задачу. Удалённую историю не вернуть.

set local lock_timeout = '3s';

-- По имени: повторный запуск обновит ту же задачу, а не заведёт вторую.
select cron.schedule(
  'cron-history-cleanup',
  '40 1 * * *',
  $job$delete from cron.job_run_details where start_time < now() - interval '3 days'$job$
);

delete from cron.job_run_details where start_time < now() - interval '3 days';
