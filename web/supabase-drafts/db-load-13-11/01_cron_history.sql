-- 1) задача cron-history-cleanup: раз в сутки в 01:40 UTC (04:40 по Москве, 05:40 по Батуми и Тбилиси) удаляет
--    историю старше 3 дней (тревогам нужны 10 минут, на разбор сбоя хватает 3 дней);
