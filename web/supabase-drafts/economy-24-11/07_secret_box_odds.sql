-- Шансы секретного бокса 70 / 22 / 6 / 2 (25.11.2026). ЧЕРНОВИК, применять только после «применяй». После 03 и 06.
--
-- Было 74 / 20 / 5 / 1. Владелец согласился: при 65 активных игроках и открытии раз в месяц легендарку почти никто
-- не видел. Теперь эпическая или легендарная — 1 из 12 открытий (было 1 из 16), легендарная — 2 из 100.
-- Средняя отдача на нынешнем каталоге с монетами ≈ 445 за 500 (было ≈ 410) — всё ещё меньше цены.
-- Меняется только выбор группы; монеты внутри (1 из 4) и повторы (половина цены) — как были.

create or replace function public._secret_box_roll() returns int language sql volatile as $$
  select case when r < 0.70 then 1 when r < 0.92 then 2 when r < 0.98 then 3 else 4 end from (select random() as r) x
$$;
revoke all on function public._secret_box_roll() from public, anon, authenticated;
