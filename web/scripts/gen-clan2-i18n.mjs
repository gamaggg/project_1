// Builds the clan update's three dictionaries (lib/i18n/clan2.{ru,en,ka}.ts) from
// one file, lib/i18n/clan2.master.json, where every key carries all three
// languages side by side — so a key can never exist in one language and miss in
// another. Run after editing the master:
//   node scripts/gen-clan2-i18n.mjs
// A leaf is an object with ru, en and ka; its values are strings or plural forms
// ({ one, few?, many?, other }). Anything else nested is a group.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const master = JSON.parse(readFileSync(join(root, 'lib/i18n/clan2.master.json'), 'utf8'))

const isLeaf = (n) => n && typeof n === 'object' && 'ru' in n && 'en' in n && 'ka' in n

function pick(node, lang, path) {
  const out = {}
  for (const [key, value] of Object.entries(node)) {
    if (key.startsWith('_')) continue
    if (isLeaf(value)) {
      if (value[lang] === undefined || value[lang] === '') throw new Error(`clan2.master.json: ${[...path, key].join('.')} has no ${lang}`)
      out[key] = value[lang]
    } else {
      out[key] = pick(value, lang, [...path, key])
    }
  }
  return out
}

function emit(node, indent) {
  const pad = '  '.repeat(indent)
  const lines = []
  for (const [key, value] of Object.entries(node)) {
    const k = /^[A-Za-z_][A-Za-z0-9_]*$/.test(key) ? key : JSON.stringify(key)
    if (typeof value === 'string') lines.push(`${pad}${k}: ${JSON.stringify(value)},`)
    else if ('other' in value) lines.push(`${pad}${k}: ${JSON.stringify(value)},`)
    else lines.push(`${pad}${k}: {\n${emit(value, indent + 1)}\n${pad}},`)
  }
  return lines.join('\n')
}

const NAMES = { ru: 'clan2Ru', en: 'clan2En', ka: 'clan2Ka' }
for (const lang of ['ru', 'en', 'ka']) {
  const body = emit(pick(master, lang, []), 1)
  const file = `// GENERATED by scripts/gen-clan2-i18n.mjs from clan2.master.json — edit the master, not this file.\nexport const ${NAMES[lang]} = {\n${body}\n}\n`
  writeFileSync(join(root, `lib/i18n/clan2.${lang}.ts`), file)
}
console.log('clan2 dictionaries written')
